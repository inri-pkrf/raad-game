// מחזיר את תמונת ה"אחרי", את תמונת ה"לפני" ואת החפצים הלחיצים, או null אם אין תמונות (אז מוצג הציור).
export function getPhotoSetup(env, levelId) {
  const key = `${env.id}-${levelId}`;
  const list = PHOTOS[key];
  if (!list) return null;
  const root = `${process.env.PUBLIC_URL || ''}/images/${key}`;
  const post = `${root}-post.jpg`;
  const pre = `${root}.jpg`;
  const sx = SCENE_SIZE[0] / 1000;
  const sy = SCENE_SIZE[1] / 1000;
  const items = list
    .map(([id, [x, y, w, h]]) => {
      const base = env.items.find((it) => it.id === id) || EXTRA_ITEMS[id];
      if (!base) return null;
      return { ...base, bbox: [x * sx, y * sy, w * sx, h * sy], photo: post };
    })
    .filter(Boolean);
  return { url: post, preUrl: pre, items };
}
